import {reviewShot,screenshotDirectory,resizeWindow} from './helpers.mjs';
/* UI, ponte HTTP e impressão reais; tutor simulado, nenhum material pessoal. */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {execFileSync} from 'node:child_process';
import {DESK,fakePiSource,launchDesk,withArtifacts,seedCourse,tinyPdf,freeMenuClick} from './helpers.mjs';
const markdown='# Grafos e relações\n\n## Lista de exercícios\n\n1. Determine os vértices de um grafo com três arestas.\n2. Discuta a transitividade de uma relação.';
const out=screenshotDirectory('course-pdf-ui');
await withArtifacts('course-pdf-ui',async ctx=>{
 const runtime=ctx.runtime=fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(),'mesa-course-pdf-ui-'))),course=seedCourse(runtime,'discreta');
 fs.writeFileSync(path.join(course,'Lista existente.pdf'),tinyPdf('Lista de exercicios'));
 const source=fakePiSource(),marker='else if(/quiz/i.test(studentText(e.message)))emitQuiz(e.message);';assert.ok(source.includes(marker));
 const branch=`else if(String(e.message).includes('Prepare um PDF na Mesa')){
  streaming=true;emit({type:'agent_start'});
  (async()=>{try{
   const {createTutorPdf}=await import(${JSON.stringify(pathToFileURL(path.join(DESK,'src/extensions/tutor-pdf/client.mjs')).href)});
   await createTutorPdf(JSON.parse(process.env.LEARNING_DESK_MATERIAL_BRIDGE),{title:'Grafos e relações',markdown:${JSON.stringify(markdown)}});
   streaming=false;emitText('Material preparado para revisar.');
  }catch(error){streaming=false;emitText('Falha: '+error.message);}})();
 } ${marker}`;
 const demo=path.join(runtime,'pi-demo.mjs');fs.writeFileSync(demo,source.replace(marker,()=>branch));fs.chmodSync(demo,0o755);
 fs.writeFileSync(path.join(runtime,'config.json'),JSON.stringify({runtimePath:runtime,vaultPath:runtime,courses:[{id:'discreta',name:'Matemática Discreta',path:course}]}));
 ctx.app=await launchDesk({runtime,env:{LEARNING_DESK_PI:demo}});const page=await ctx.app.firstWindow();
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.waitForSelector('#study-tutor-pdf',{state:'attached'});
 await page.evaluate(async()=>{const {S,connect}=await import('./src/state.mjs');window.__studyState=S;if(!S.connected)await connect();});
 await page.waitForFunction(()=>window.__studyState.connected&&!window.__studyState.busy);
 await page.locator('#study-menu .nav-trigger').click();await page.locator('#study-tutor-pdf').click();await page.locator('#tutor-pdf-request').fill('Prepare uma lista seguindo a estrutura da Lista existente.pdf.');
 await page.locator('#tutor-pdf-send').click();
 await page.waitForFunction(()=>document.querySelector('#free-pdf-dialog').open&&!window.__studyState.busy);
 assert.equal(await page.locator('#free-pdf-content').inputValue(),markdown);
 assert.equal(fs.existsSync(path.join(course,'Materiais da Mesa')),false,'prévia não gera arquivo');
 await reviewShot(page,out,'01-previa-na-materia.png');
 await page.keyboard.press('Escape');await page.reload();await page.waitForSelector('#tutor-material-status button');
 await page.locator('#tutor-material-status button').click();assert.equal(await page.locator('#free-pdf-content').inputValue(),markdown);
 await page.locator('#free-pdf-content').fill(markdown+'\n\nNota revisada pelo aluno.');
 await page.locator('#free-pdf-save').click();
 await page.waitForFunction(()=>!document.querySelector('#free-pdf-dialog').open&&!!document.querySelector('.pdf-page[data-rendered] canvas'),undefined,{timeout:60000});
 const generated=path.join(course,'Materiais da Mesa','Grafos-e-relacoes.pdf');
 const files=fs.readdirSync(path.dirname(generated));assert.equal(files.length,1);
 assert.match(execFileSync('pdftotext',[path.join(path.dirname(generated),files[0]),'-'],{encoding:'utf8'}),/Nota revisada/);
 await page.locator('#course-tabs button[data-id="mesa-free"]').click();await page.waitForSelector('#free-bar:not([hidden])');
 await page.evaluate(async()=>{const {S}=await import('./src/state.mjs');window.__studyState=S;});
 await freeMenuClick(page,'#free-generate-pdf');await page.locator('#free-pdf-title').fill('Resumo de relações');await page.locator('#free-pdf-content').fill(markdown);
 await page.locator('#free-pdf-save').click();await page.waitForFunction(()=>!document.querySelector('#free-pdf-dialog').open&&window.__studyState.workspace.materials.length===1,undefined,{timeout:60000});
 const original=await page.evaluate(()=>window.__studyState.workspace.materials[0].path),before=fs.readFileSync(original);
 await freeMenuClick(page,'#free-add-material');await page.locator('#free-add-course').selectOption('discreta');
 await reviewShot(page,out,'02-adicionar-a-materia.png');
 await page.locator('#free-add-save').click();await page.waitForFunction(()=>!document.querySelector('#free-add-dialog').open);
 assert.deepEqual(fs.readFileSync(original),before);
 assert.equal(fs.readdirSync(path.join(course,'Materiais da Mesa')).length,2);
 await page.locator('#course-tabs button[data-id="discreta"]').click();await page.waitForSelector('#study-tutor-pdf',{state:'attached'});
 const library=await page.evaluate(async()=>(await window.desk.init()).library);assert.ok(library.some(p=>p.name.includes('Resumo')));
 await resizeWindow(ctx.app,page,900,650);
 await page.locator('#study-menu .nav-trigger').click();await page.locator('#study-tutor-pdf').click();const bounds=await page.locator('#tutor-pdf-dialog').boundingBox();assert.ok(bounds.x>=0&&bounds.y>=0&&bounds.x+bounds.width<=900&&bounds.y+bounds.height<=650);
 assert.deepEqual(errors,[]);
 console.log('COURSE PDF UI PASSED: tutor na matéria, prévia persistida, PDF real revisado, Livre→matéria, original preservado, biblioteca e 900x650. Tutor simulado.');
});
