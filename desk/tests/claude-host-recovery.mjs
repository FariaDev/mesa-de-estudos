// Electron/IPC recovery with artificial data only. No native Claude process.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {withArtifacts,newRuntime,seedCourse,writeDeskJson,writeConfigJson,launchDesk,DESK} from './helpers.mjs';
const conversations=createRequire(import.meta.url)('../src/agents/conversations.cjs');
await withArtifacts('claude-recovery',async ctx=>{
 const runtime=ctx.runtime=newRuntime('claude-recovery'),folder=seedCourse(runtime,'Recovery');
 const file=conversations.createClaudeConversation({runtime,courseId:'Recovery'});
 conversations.updateClaudeConversation(file,{delivery:{id:'in-flight',status:'accepted'},messages:[{role:'user',content:[{type:'text',text:'Artificial question'}]},{role:'assistant',content:[{type:'text',text:'Cached artificial answer'}]}]},{runtime});
 const starts=path.join(runtime,'pi-starts'),trap=path.join(runtime,'pi-trap.sh');
 fs.writeFileSync(trap,`#!/bin/sh\nprintf started >> '${starts}'\nexit 1\n`,{mode:0o755});
 writeConfigJson(runtime,{vaultPath:runtime,courses:[{id:'Recovery',name:'Recovery',path:folder}]});
 writeDeskJson(runtime,{courseId:'Recovery',session:file,courseStates:{Recovery:{session:file,sessions:[{path:file}]}}});
 const launch=()=>launchDesk({runtime,pi:false,env:{LEARNING_DESK_PI:trap,LEARNING_DESK_CLAUDE_SDK_FACTORY:path.join(DESK,'tests','fixtures','claude-sdk-fake.mjs')}});
 let app=ctx.app=await launch(),page=await app.firstWindow();
 await page.waitForSelector('.pdf-panel');
 const recovered=await page.evaluate(()=>window.desk.init());
 assert.equal(recovered.engine,'claude');assert.equal(recovered.conversationStatus.uncertain,true);
 const health=await page.evaluate(()=>window.desk.health());
 assert.equal(health.engine,'claude');assert.equal(Object.hasOwn(health,'messages'),false,'health IPC omits the image/history payload');
 const controlsRefused=await page.evaluate(async()=>{try{await window.desk.settings({model:{provider:'anthropic',id:'claude-fake'},level:'max'});return '';}catch(error){return error.message;}});
 assert.match(controlsRefused,/incerta/,'persisted uncertainty locks settings after reopening');
 assert.equal(await page.locator('#model-select').isDisabled(),true);
 assert.equal(await page.locator('#thinking-select').isDisabled(),true);
 const declined=await page.evaluate(()=>window.desk.prompt({text:'Do not retry',refs:[]}));
 assert.equal(declined.sent,false);assert.equal(declined.retryable,false);
 assert.equal(conversations.readClaudeConversation(file,{runtime}).delivery.status,'uncertain');
 assert.equal(fs.existsSync(starts),false,'Claude recovery must never launch Pi');
 await app.close();
 const corrupt='{corrupt';fs.writeFileSync(file,corrupt);
 app=ctx.app=await launch();page=await app.firstWindow();await page.waitForSelector('.pdf-panel');
 const broken=await page.evaluate(()=>window.desk.init());
 assert.equal(broken.engine,'claude');assert.equal(broken.conversationStatus.invalid,true);
 const replacement=await page.evaluate(()=>window.desk.newSession('claude'));
 assert.equal(replacement.engine,'claude');assert.notEqual(replacement.session,file);
 assert.equal(fs.readFileSync(file,'utf8'),corrupt,'corruption is preserved for recovery');
 assert.equal(fs.existsSync(starts),false,'corrupt descriptor must never launch Pi');
 await page.evaluate(()=>window.desk.connect());
 const sent=await page.evaluate(()=>window.desk.prompt({text:'artificial pipeline',refs:[],images:[]}));
 assert.notEqual(sent.sent,false);
 for(let tries=0;tries<100&&conversations.readClaudeConversation(replacement.session,{runtime}).delivery?.status!=='settled';tries++)await new Promise(r=>setTimeout(r,20));
 const final=conversations.readClaudeConversation(replacement.session,{runtime});
 assert.equal(final.delivery.status,'settled','receipt and final result were persisted by the real host');
 assert.equal(final.nativeEstablished,true);
 assert.equal(final.messages[0].role,'user');assert.equal(final.messages[1].role,'assistant');
 // A native transcript larger than the display prefix must export all pages,
 // even when the descriptor only contains the two recent cached messages.
 const nativeDir=path.join(runtime,'claude-workspaces',final.id,'.claude-fake-sessions');
 fs.mkdirSync(nativeDir,{recursive:true});
 const nativeMessages=Array.from({length:501},(_,index)=>({type:'assistant',uuid:`native-${index}`,message:{role:'assistant',content:[{type:'text',text:`Artificial native row ${index}`} ]}}));
 fs.writeFileSync(path.join(nativeDir,`session-${final.nativeSessionId}.json`),JSON.stringify({messages:nativeMessages}));
 const exported=await page.evaluate(()=>window.desk.exportChat());
 assert.equal(exported.saved,true);
 const markdown=fs.readFileSync(exported.file,'utf8');
 assert.match(markdown,/Artificial native row 500/,'export reaches beyond the 200-row display limit');
 assert.equal((markdown.match(/## Claude\b/g)||[]).length,501,'native pagination has neither duplicate nor missing rows');
 assert.equal(fs.existsSync(starts),false,'sending through Claude must never launch Pi');
 console.log('CLAUDE RECOVERY PASSED: uncertain delivery held; corrupt descriptor preserved; new conversation available; 501 native rows exported; zero Pi starts.');
});
