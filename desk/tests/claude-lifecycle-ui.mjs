// Electron integration with artificial course, SDK, account and session only.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {withArtifacts,newRuntime,seedCourse,writeDeskJson,writeConfigJson,launchDesk,sendEnabled,statusOnline,toastWait,DESK} from './helpers.mjs';
const conversations=createRequire(import.meta.url)('../src/agents/conversations.cjs');
await withArtifacts('claude-lifecycle',async ctx=>{
 const runtime=ctx.runtime=newRuntime('claude-lifecycle'),folder=seedCourse(runtime,'Lifecycle');
 const file=conversations.createClaudeConversation({runtime,courseId:'Lifecycle'});
 const log=path.join(runtime,'prompts.log'),trace=path.join(runtime,'trace.log');
 writeConfigJson(runtime,{vaultPath:runtime,courses:[{id:'Lifecycle',name:'Lifecycle',path:folder}]});
 writeDeskJson(runtime,{courseId:'Lifecycle',session:file,courseStates:{Lifecycle:{session:file,sessions:[{path:file}]}}});
 const id=conversations.readClaudeConversation(file,{runtime}).nativeSessionId;
 const app=ctx.app=await launchDesk({runtime,pi:false,env:{FAKE_CLAUDE_LOG:log,FAKE_CLAUDE_TRACE:trace,FAKE_CLAUDE_RATE_DELAY_MS:'1500',LEARNING_DESK_CLAUDE_SDK_FACTORY:path.join(DESK,'tests','fixtures','claude-sdk-fake.mjs')}});
 const page=await app.firstWindow();await statusOnline(page,{timeout:60000});
 const record=()=>conversations.readClaudeConversation(file,{runtime});
 const submit=async text=>{await page.locator('#prompt').fill(text);await page.locator('#send').click();};
 const body=async text=>page.waitForFunction(t=>[...document.querySelectorAll('.message.assistant .body')].some(el=>el.textContent.includes(t)),text,{timeout:30000});
 await submit('[claude:no-echo]');await body('[claude:no-echo]');await sendEnabled(page);
 assert.equal(record().delivery.status,'settled','accepted result without UUID settles');
 await submit('[claude:question]');await page.waitForSelector('#pi-dialog[open][data-question="true"]');
 await page.locator('#dialog-ok').click();
 assert.equal(await page.locator('#pi-dialog').evaluate(el=>el.open),true,'missing answers keep dialog open');
 await page.locator('.cq-question[data-cq-index="0"] input[value="Detalhado"]').check();
 await page.locator('.cq-question[data-cq-index="1"] input[value="Álgebra"]').check();
 await page.locator('.cq-question[data-cq-index="1"] input[value="Gráfico"]').check();
 await page.locator('#dialog-ok').click();await body('Álgebra, Gráfico');await sendEnabled(page);
 await submit('[claude:question]');await page.waitForSelector('#pi-dialog[open][data-question="true"]');
 await page.locator('.cq-question[data-cq-index="0"] .cq-text-input').fill('Outro caminho');
 await page.locator('.cq-question[data-cq-index="1"] .cq-text-input').fill('Outra revisão');
 await page.locator('#dialog-ok').click();await body('Outro caminho');await sendEnabled(page);
 await submit('[claude:question]');await page.waitForSelector('#pi-dialog[open][data-question="true"]');
 await page.locator('#pi-dialog button[value="cancel"]').click();await body('Perguntas canceladas');await sendEnabled(page);
 await submit('[claude:rate-limit]');
 await page.waitForFunction(()=>/limite/i.test(document.querySelector('#activity').textContent),undefined,{timeout:30000});
 assert.equal(await page.locator('#status-dot').evaluate(el=>el.classList.contains('online')),true);
 assert.equal(await page.locator('#stop').isVisible(),true,'limit warning preserves active turn');
 await body('Limite liberado');await sendEnabled(page);
 await submit('[claude:retry]');
 await page.waitForFunction(()=>/tentativa.*2.*4/i.test(document.querySelector('#activity').textContent));
 assert.equal(await page.locator('#stop').isVisible(),true,'native retry does not settle the active turn');
 await body('Retry concluído');await sendEnabled(page);await statusOnline(page);
 await submit('[claude:fallback]');await toastWait(page,'Troca de modelo artificial');
 await body('Fallback concluído');await sendEnabled(page);await statusOnline(page);
 await submit('[claude:multiple-rate]');
 await page.waitForFunction(()=>/7 dias/i.test(document.querySelector('#activity').textContent));
 await page.waitForTimeout(700);
 assert.match(await page.locator('#activity').textContent(),/7 dias/,'one released window cannot hide the other blocked window');
 await body('Janelas liberadas');await sendEnabled(page);
 for(const marker of ['context-error','blocking-limit']){
  await submit(`[claude:${marker}]`);await body(`[claude:${marker}]`);await sendEnabled(page);await statusOnline(page);
  assert.equal(record().delivery.status,'settled','native result failure preserves accepted delivery');
 }
 await submit('[claude:interrupt-exit]');await page.waitForSelector('#stop:not([hidden])');
 await page.waitForFunction(()=>document.querySelector('#send').disabled);
 await page.locator('#stop').click();await sendEnabled(page,{timeout:30000});
 assert.equal(record().delivery.status,'settled','accepted cancellation with query exit is settled');
 await submit('after interrupt exit');await body('after interrupt exit');await sendEnabled(page);
 assert.equal(record().nativeSessionId,id);
 const queries=fs.readFileSync(trace,'utf8').trim().split('\n').map(JSON.parse).filter(row=>row.event==='query');
 assert.ok(queries.length>=2,'query reopened after interruption');
 assert.equal(queries.at(-1).resume,id,'reopened query resumes same native session');
 assert.equal(queries.at(-1).newSession,null,'resume does not also specify a new session');
 console.log('CLAUDE LIFECYCLE UI PASSED: no-echo; structured single/multi/free/cancel questions; visible limits; interrupt-exit and native resume.');
});
